import functools

def log_call(func):                              # takes a function…
    @functools.wraps(func)                       # (keeps the name and docstring)
    def wrapper(*args, **kwargs):
        print(f"→ calling {func.__name__}{args}")
        result = func(*args, **kwargs)           # run the original
        print(f"← {func.__name__} returned {result!r}")
        return result
    return wrapper                               # …returns a wrapped one

@log_call                                        # same as: get_price = log_call(get_price)
def get_price(item: str, qty: int = 1) -> int:
    """Return the total price in rupees for qty of an item on the menu."""
    return MENU[item.lower().strip()] * qty

